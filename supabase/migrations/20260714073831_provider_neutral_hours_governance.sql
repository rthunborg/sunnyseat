    check (outcome in (
      'current',
      'missing_provenance',
      'due',
      'unknown',
      'conflicting',
      'split',
      'failed',
      'stale'
    )),
  constraint hours_review_outcomes_reason_check
    check (reason in (
      'review_current',
      'missing_provenance',
      'review_due',
      'hours_unknown',
      'provenance_conflict',
      'unsupported_split',
      'prior_failure',
      'review_stale',
      'classification_failed'
    )),
