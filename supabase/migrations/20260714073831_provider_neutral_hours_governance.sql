create or replace function public.claim_hours_review_run(
  p_run_id text,
  p_trigger_type text,
  p_started_at timestamptz default now()
)
returns boolean
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  inserted_count integer;
begin
  insert into public.hours_review_runs (id, trigger_type, status, started_at)
  values (p_run_id, p_trigger_type, 'running', p_started_at)
  on conflict do nothing;

  get diagnostics inserted_count = row_count;
  return inserted_count = 1;
end;
$$;

create or replace function public.finish_hours_review_run(
  p_run_id text,
  p_status text,
  p_finished_at timestamptz,
  p_total_count integer,
  p_current_count integer,
  p_missing_provenance_count integer,
  p_due_count integer,
  p_unknown_count integer,
  p_conflicting_count integer,
  p_split_count integer,
  p_failed_count integer,
  p_stale_count integer
)
returns boolean
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  update public.hours_review_runs
  set status = p_status,
      finished_at = p_finished_at,
      total_count = p_total_count,
      current_count = p_current_count,
      missing_provenance_count = p_missing_provenance_count,
      due_count = p_due_count,
      unknown_count = p_unknown_count,
      conflicting_count = p_conflicting_count,
      split_count = p_split_count,
      failed_count = p_failed_count,
      stale_count = p_stale_count
  where id = p_run_id and status = 'running';

  return found;
end;
$$;

create or replace function public.prune_hours_review_history(
  p_cutoff timestamptz default (now() - interval '180 days')
)
returns integer
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  deleted_count integer;
begin
  delete from public.hours_review_runs
  where coalesce(finished_at, started_at) < p_cutoff
    and status <> 'running';

  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

