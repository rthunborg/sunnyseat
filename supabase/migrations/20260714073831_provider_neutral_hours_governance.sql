-- Canonical public hours remain public.venues.opening_hours (nullable jsonb).
-- Provenance and review operations are service-only and never projected into
-- public DTOs. Existing rows remain deployable before the one-time remediation:
-- provenance fields are nullable and no old schedule is relabelled automatically.

