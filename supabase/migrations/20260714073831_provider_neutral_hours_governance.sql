-- Story 12.1: Place-ID-only, provider-neutral opening-hours governance.
-- Canonical public hours remain public.venues.opening_hours (nullable jsonb).
-- Provenance and review operations are service-only and never projected into
-- public DTOs. Existing rows remain deployable before the one-time remediation:
-- provenance fields are nullable and no old schedule is relabelled automatically.

alter table public.venues
  drop column if exists places_api_url,
  add column if not exists hours_source_type text,
  add column if not exists hours_source_reference text,
  add column if not exists hours_review_status text,
  add column if not exists hours_reviewed_at timestamptz,
  add column if not exists hours_next_review_at timestamptz,
  add column if not exists hours_notes text;

alter table public.venues
  alter column opening_hours drop not null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'venues_hours_source_type_check'
      and conrelid = 'public.venues'::regclass
  ) then
    alter table public.venues add constraint venues_hours_source_type_check
      check (
        hours_source_type is null or hours_source_type in (
          'venue_confirmed',
          'venue_website',
          'licensed_provider',
          'manual'
        )
      );
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'venues_hours_review_status_check'
      and conrelid = 'public.venues'::regclass
  ) then
    alter table public.venues add constraint venues_hours_review_status_check
      check (
        hours_review_status is null or hours_review_status in (
          'verified',
          'due',
          'manual_review',
          'unknown',
          'failed'
        )
      );
  end if;

  if not exists (
    select 1 from pg_constraint
    where conname = 'venues_hours_review_dates_check'
      and conrelid = 'public.venues'::regclass
  ) then
    alter table public.venues add constraint venues_hours_review_dates_check
      check (
        hours_next_review_at is null
        or hours_reviewed_at is null
        or hours_next_review_at >= hours_reviewed_at
      );
  end if;
end
$$;

create index if not exists venues_place_id_idx
  on public.venues (place_id)
  where place_id is not null;

create index if not exists venues_hours_next_review_at_idx
  on public.venues (hours_next_review_at)
  where hours_next_review_at is not null;

create table if not exists public.hours_review_runs (
  id text primary key,
  trigger_type text not null,
  status text not null default 'running',
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  total_count integer not null default 0 check (total_count >= 0),
  current_count integer not null default 0 check (current_count >= 0),
  missing_provenance_count integer not null default 0 check (missing_provenance_count >= 0),
  due_count integer not null default 0 check (due_count >= 0),
  unknown_count integer not null default 0 check (unknown_count >= 0),
  conflicting_count integer not null default 0 check (conflicting_count >= 0),
  split_count integer not null default 0 check (split_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  stale_count integer not null default 0 check (stale_count >= 0),
  constraint hours_review_runs_trigger_type_check
    check (trigger_type in ('scheduled', 'manual', 'remediation')),
  constraint hours_review_runs_status_check
    check (status in ('running', 'completed', 'completed_with_failures', 'failed')),
  constraint hours_review_runs_finished_at_check
    check ((status = 'running' and finished_at is null) or (status <> 'running' and finished_at is not null))
);

create table if not exists public.hours_review_outcomes (
  id bigint generated by default as identity primary key,
  run_id text not null references public.hours_review_runs(id) on delete cascade,
  venue_id text not null references public.venues(id) on delete cascade,
  venue_slug text not null check (char_length(venue_slug) between 1 and 200),
  outcome text not null,
  reason text not null,
  error_class text,
  created_at timestamptz not null default now(),
  constraint hours_review_outcomes_run_venue_key unique (run_id, venue_id),
  constraint hours_review_outcomes_outcome_check
    check (outcome in (
      'current',
      'missing_provenance',
      'due',
      'unknown',
      'conflicting',
      'split',
      'failed',
      'stale'
    )),
  constraint hours_review_outcomes_reason_check
    check (reason in (
      'review_current',
      'missing_provenance',
      'review_due',
      'hours_unknown',
      'provenance_conflict',
      'unsupported_split',
      'prior_failure',
      'review_stale',
      'classification_failed'
    )),
  constraint hours_review_outcomes_error_class_check
    check (
      error_class is null or error_class in (
        'read_failed',
        'validation_failed',
        'database_error',
        'unexpected'
      )
    )
);

create index if not exists hours_review_runs_started_at_idx
  on public.hours_review_runs (started_at desc);

create index if not exists hours_review_outcomes_run_id_idx
  on public.hours_review_outcomes (run_id);

create index if not exists hours_review_outcomes_venue_id_created_at_idx
  on public.hours_review_outcomes (venue_id, created_at desc);

-- Atomic non-overlap: at most one active run may hold status='running'. The
-- partial unique index makes the claim race-safe across independent workers.
create unique index if not exists hours_review_runs_one_active_run_idx
  on public.hours_review_runs ((status))
  where status = 'running';

